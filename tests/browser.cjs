// End-to-end smoke checks against an isolated database and a real browser.
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const assert=require('node:assert/strict');
const data=fs.mkdtempSync(path.join(os.tmpdir(),'neurostudy-browser-'));
const port=process.env.STUDY_TEST_PORT||'8011';
const base=`http://127.0.0.1:${port}`;
const server=spawn('.venv/bin/python',['-m','uvicorn','app.main:app','--host','127.0.0.1','--port',port],{
  env:{...process.env,STUDY_DATA_DIR:data,STUDY_AI_KEY:'',STUDY_PASSWORD:''},stdio:['ignore','ignore','pipe']});
let log='';server.stderr.on('data',s=>log+=s);
let browser;
(async()=>{
  for(let n=0;n<80;n++){
    if(server.exitCode!==null)throw Error(log);
    try{if((await fetch(base+'/api/status')).ok)break;}catch{}
    await new Promise(r=>setTimeout(r,100));
  }
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.setDefaultTimeout(15000);
  await page.goto(base);
  await page.getByLabel('Password',{exact:true}).fill('browser-test-password-123');
  await page.locator('#login-form button').click();
  await page.getByRole('heading',{name:'Ogni giorno, un passo avanti.'}).waitFor();
  fs.mkdirSync('test-results',{recursive:true});
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  // Real upload -> literal generation -> reviewed content -> quiz.
  await page.getByRole('link',{name:'I miei materiali',exact:true}).click();
  await page.getByRole('button',{name:'+ Carica materiale'}).click();
  const text='La miastenia presenta debolezza fluttuante e affaticabilità muscolare. La sensibilità generalmente rimane conservata nella malattia della giunzione neuromuscolare.';
  await page.locator('input[type=file]').setInputFiles({name:'Appunti browser.txt',mimeType:'text/plain',buffer:Buffer.from(text)});
  await page.getByRole('button',{name:'Carica ed estrai il testo'}).click();
  await page.getByRole('heading',{name:'Appunti browser.txt',exact:true}).waitFor();
  await page.getByRole('button',{name:'Genera quiz o flashcard'}).click();
  await page.locator('[name=document_ids]').check();
  await page.locator('[name=count]').fill('1');
  await page.getByRole('button',{name:'Genera e salva nel database'}).click();
  await page.getByRole('heading',{name:'Generazione completata'}).waitFor();
  await page.getByRole('link',{name:'Apri i contenuti'}).click();
  await page.getByRole('button',{name:'Modifica / approva'}).click();
  await page.locator('[name=review_required]').uncheck();
  await page.getByRole('button',{name:'Salva la revisione'}).click();
  await page.getByRole('button',{name:'Inizia una sessione'}).click();
  await page.getByRole('button',{name:'Comincia il quiz'}).click();
  await page.getByRole('heading',{name:'Allenamento quiz'}).waitFor();
  await page.locator('.option input').first().check();
  await page.getByRole('button',{name:'Conferma risposta'}).click();
  await page.locator('.sources summary').waitFor();
  await page.screenshot({path:'test-results/quiz-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Crea flashcard'}).click();
  await page.getByRole('button',{name:'Conferma e crea flashcard'}).click();
  await page.getByRole('link',{name:'Flashcard',exact:true}).click();
  await page.getByRole('button',{name:'Inizia il ripasso'}).click();
  await page.locator('#review-start-form button').click();
  await page.getByRole('button',{name:'Mostra la risposta'}).click();
  await page.getByRole('button',{name:'Bene · intervallo adattivo'}).click();
  await page.getByRole('heading',{name:'Un altro passo avanti.'}).waitFor();
  await page.getByRole('link',{name:'Casi clinici',exact:true}).click();
  await page.getByRole('button',{name:'Apri il caso'}).click();
  await page.getByRole('heading',{name:'Un paziente. Il tuo ragionamento.'}).waitFor();
  await page.getByRole('button',{name:'Esordio e andamento dei sintomi'}).click();
  await page.locator('.event').first().waitFor();
  await page.getByLabel('Chiedi al paziente o richiedi un accertamento').fill('Voglio un esame');
  await page.getByRole('button',{name:'Invia richiesta'}).click();
  await page.getByText('Da chiarire · nessun esame richiesto').waitFor();
  await page.getByLabel('Ipotesi, localizzazione e differenziali').fill('Appunti persistenti del browser');
  await page.getByRole('link',{name:'Salva ed esci'}).click();
  await page.getByRole('heading',{name:'Ogni giorno, un passo avanti.'}).waitFor();
  const resume=page.locator('a[href^="#session/case/"]').first();await resume.click();
  await page.getByLabel('Ipotesi, localizzazione e differenziali').waitFor();
  assert.equal(await page.locator('#case-notes').inputValue(),'Appunti persistenti del browser');
  await page.screenshot({path:'test-results/case-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Concludi il caso'}).click();
  await page.getByLabel('Diagnosi principale').fill('miastenia gravis');
  await page.getByRole('button',{name:'Consegna e scopri il feedback'}).click();
  await page.getByRole('heading',{name:'Guarda il percorso, oltre la risposta.'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/#dashboard');
  await page.getByRole('heading',{name:'Ogni giorno, un passo avanti.'}).waitFor();
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'overflow mobile');
  await page.getByRole('button',{name:'Impostazioni',exact:true}).first().click();
  await page.getByRole('button',{name:'Cambia tema'}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.getByRole('button',{name:'Chiudi finestra'}).click();
  await page.screenshot({path:'test-results/dashboard-dark-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser: upload → generazione → quiz → flashcard → ripasso → caso → ripresa → valutazione; mobile e tema scuro: OK');
})().catch(e=>{console.error(e,log);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM');fs.rmSync(data,{recursive:true,force:true});});
